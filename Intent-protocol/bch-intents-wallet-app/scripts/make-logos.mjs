// Writes src/ui/logos.ts from the SVG logos of the browser extension, so both wallets draw the same marks.
// The chain table names a logo by its web path ('/logos/solana.svg'); the app looks the same path up here.
//
//   node scripts/make-logos.mjs [path to the extension's public/logos]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] ?? join(root, '..', 'bch-intents-wallet-extension', 'public', 'logos');

const FILES = [
  'bitcoin-cash-bch-logo.svg', 'ethereum-eth-logo.svg', 'Base_square_blue.svg', 'arbitrum-arb-logo.svg',
  'optimism.svg', 'arc.svg', 'solana.svg', 'bitcoin.svg', 'usd-coin-usdc-logo.svg',
];

const entries = FILES.map(file => {
  const svg = readFileSync(join(source, file), 'utf8')
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `  '/logos/${file}': ${JSON.stringify(svg)},`;
});

writeFileSync(join(root, 'src', 'ui', 'logos.ts'), `// Generated by scripts/make-logos.mjs from the extension's public/logos. Do not edit by hand.

/** SVG source by the web path the shared chain table uses. */
export const LOGOS: Record<string, string> = {
${entries.join('\n')}
};
`);
console.log(`wrote ${entries.length} logos`);
